def get_scenario(name: str | None) -> dict:
    if name is None:
        return SCENARIOS["suspicious_high_value"]
    key = name.strip().lower()
    for scenario_key, scenario in SCENARIOS.items():
        if scenario_key == key or scenario["name"].lower() == key:
            return scenario
    raise ValueError(f"Unknown scenario '{name}'. Choose from: {', '.join(SCENARIOS.keys())}.")
